/* 确认：若本次会关闭正在供电的关键轨(DCDC3/LDO2)，先弹二次确认；否则直接生效 */
static void dlg_confirm_cb(lv_event_t *e)
{
    (void)e;
    bool danger = false;
    for (int i = 0; i < AXP202_RAIL_COUNT; i++) {
        bool want = lv_obj_has_state(s_rail_sw[i], LV_STATE_CHECKED);
        if (rail_is_critical(i) && rail_current_on(i) && !want) {
            danger = true;   /* 正在供电的关键轨即将被关闭 */
            break;
        }
    }

    if (danger) {
        power_confirm2_open();   /* 二次确认，用户点“仍要关闭”后才 power_commit */
    } else {
        power_commit();
    }
}

