void app_main(void)
{
    ESP_LOGI(TAG, "Install QEMU virtual RGB panel (%dx%d)", LCD_H_RES, LCD_V_RES);
    const esp_lcd_rgb_qemu_config_t panel_cfg = {
        .width  = LCD_H_RES,
        .height = LCD_V_RES,
        .bpp    = RGB_QEMU_BPP_16,
    };
    ESP_ERROR_CHECK(esp_lcd_new_rgb_qemu(&panel_cfg, &s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_reset(s_panel));
    ESP_ERROR_CHECK(esp_lcd_panel_init(s_panel));

    ESP_LOGI(TAG, "Initialize LVGL");
    lv_init();

    s_disp = lv_display_create(LCD_H_RES, LCD_V_RES);
    lv_display_set_color_format(s_disp, LV_COLOR_FORMAT_RGB565);
    lv_display_set_flush_cb(s_disp, lvgl_flush_cb);

    static uint8_t buf1[LCD_H_RES * LVGL_BUF_LINES * 2];
    static uint8_t buf2[LCD_H_RES * LVGL_BUF_LINES * 2];
    lv_display_set_buffers(s_disp, buf1, buf2, sizeof(buf1), LV_DISPLAY_RENDER_MODE_PARTIAL);

    const esp_timer_create_args_t tick_args = {
        .callback = &lvgl_tick_cb,
        .name = "lvgl_tick",
    };
    esp_timer_handle_t tick_timer = NULL;
    ESP_ERROR_CHECK(esp_timer_create(&tick_args, &tick_timer));
    ESP_ERROR_CHECK(esp_timer_start_periodic(tick_timer, LVGL_TICK_PERIOD_MS * 1000));

    s_lvgl_mux = xSemaphoreCreateRecursiveMutex();
    assert(s_lvgl_mux);
    xTaskCreate(lvgl_task, "LVGL", LVGL_TASK_STACK, NULL, LVGL_TASK_PRIORITY, NULL);

    ESP_LOGI(TAG, "Build AXP202 dashboard (QEMU RGB, simulated data)");
    if (lvgl_lock(-1)) {
        axp202_ui_create();
        lv_timer_create(data_timer_cb, 1000, NULL);
        /* QEMU 无触摸输入，用脚本化定时器演示浮窗交互（弹窗→改开关→确认）*/
        lv_timer_create(demo_seq_cb, 2000, NULL);
        lvgl_unlock();
    }
    ESP_LOGI(TAG, "AXP202 dashboard is running");
}

