/* ===================== Refresh the dynamic widgets from s_axp ===================== */

static void ui_refresh_dynamic(void)
{
    char b[48];

    int pct = s_axp.batt_pct < 0 ? 0 : s_axp.batt_pct;
    lv_label_set_text_fmt(s_batt_lbl, "%d%% %s%s", pct,
                          s_axp.charging ? LV_SYMBOL_CHARGE : "", LV_SYMBOL_BATTERY_FULL);

    snprintf(b, sizeof(b), "%.2f V", s_axp.vbat_v);
    lv_label_set_text(s_vbat_lbl, b);

    if (s_axp.charging) {
        snprintf(b, sizeof(b), LV_SYMBOL_CHARGE " charging  %.0f mA", s_axp.ibat_ma);
    } else {
        snprintf(b, sizeof(b), "discharge  %.0f mA", -s_axp.ibat_ma);
    }
    lv_label_set_text(s_ibat_lbl, b);

    lv_bar_set_value(s_batt_bar, pct, LV_ANIM_OFF);

    snprintf(b, sizeof(b), "ACIN   %.2f V   %.0f mA", s_axp.acin_v, s_axp.acin_ma);
    lv_label_set_text(s_acin_lbl, b);
    snprintf(b, sizeof(b), "VBUS   %.2f V   %.0f mA", s_axp.vbus_v, s_axp.vbus_ma);
    lv_label_set_text(s_vbus_lbl, b);

    snprintf(b, sizeof(b), "%.1f C", s_axp.temp_c);
    lv_label_set_text(s_temp_lbl, b);
}

