static void rails_reload(void)
{
    if (!s_rails_card) {
        return;
    }
    lv_obj_clean(s_rails_card);
    rails_fill(s_rails_card);
}

/* Apply one rail on/off: drive real AXP202 on hardware, always update UI cache. */
static void power_apply_rail(int idx, bool on)
{
#if !CONFIG_AXP202_UI_PANEL_QEMU_RGB
    axp202_set_rail((axp202_rail_t)idx, on);
#endif
    switch (idx) {
    case AXP202_RAIL_DCDC2: s_axp.dcdc2_on = on; break;
    case AXP202_RAIL_DCDC3: s_axp.dcdc3_on = on; break;
    case AXP202_RAIL_LDO2:  s_axp.ldo2_on  = on; break;
    case AXP202_RAIL_LDO3:  s_axp.ldo3_on  = on; break;
    case AXP202_RAIL_LDO4:  s_axp.ldo4_on  = on; break;
    case AXP202_RAIL_EXTEN: s_axp.exten    = on; break;
    default: break;
    }
}

static void power_dialog_close(void)
{
    if (s_dlg_bg) {
        lv_obj_del(s_dlg_bg);
        s_dlg_bg = NULL;
    }
}

/* 关键电源轨：关闭会断电/黑屏（DCDC3=主控供电，LDO2=屏幕与SD卡供电）*/
static bool rail_is_critical(int idx)
{
    return idx == AXP202_RAIL_DCDC3 || idx == AXP202_RAIL_LDO2;
}

/* 该轨当前（UI 缓存中的）使能状态 */
static bool rail_current_on(int idx)
{
    switch (idx) {
    case AXP202_RAIL_DCDC2: return s_axp.dcdc2_on;
    case AXP202_RAIL_DCDC3: return s_axp.dcdc3_on;
    case AXP202_RAIL_LDO2:  return s_axp.ldo2_on;
    case AXP202_RAIL_LDO3:  return s_axp.ldo3_on;
    case AXP202_RAIL_LDO4:  return s_axp.ldo4_on;
    case AXP202_RAIL_EXTEN: return s_axp.exten;
    default: return false;
    }
}

/* 真正应用开关面板：逐路落地 + 刷新主卡片 + 关开关浮窗 */
static void power_commit(void)
{
    for (int i = 0; i < AXP202_RAIL_COUNT; i++) {
        bool on = lv_obj_has_state(s_rail_sw[i], LV_STATE_CHECKED);
        power_apply_rail(i, on);
    }
#if !CONFIG_AXP202_UI_PANEL_QEMU_RGB
    axp_pull_live();   /* 回读硬件真实状态 */
#endif
    rails_reload();
    power_dialog_close();
}

static void power_confirm2_close(void)
{
    if (s_confirm2_bg) {
        lv_obj_del(s_confirm2_bg);
        s_confirm2_bg = NULL;
    }
}

/* 二次确认——返回：不生效，回到开关浮窗 */
static void confirm2_back_cb(lv_event_t *e)
{
    (void)e;
    power_confirm2_close();
}

/* 二次确认——仍要关闭：生效并关闭两层浮窗 */
static void confirm2_accept_cb(lv_event_t *e)
{
    (void)e;
    power_confirm2_close();
    power_commit();
}

