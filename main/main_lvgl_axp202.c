/* ===================== Periodic data update ===================== */

static void data_timer_cb(lv_timer_t *t)
{
#if CONFIG_AXP202_UI_PANEL_QEMU_RGB
    /* QEMU：无真实 PMU，模拟一个“活着”的仪表盘 */
    static int sec = 45, mn = 42, hr = 15;
    if (++sec >= 60) { sec = 0; if (++mn >= 60) { mn = 0; hr = (hr + 1) % 24; } }
    lv_label_set_text_fmt(s_time_lbl, "%02d:%02d:%02d", hr, mn, sec);

    s_axp.ibat_ma = 132.0f + (float)((int)lv_rand(0, 160) - 80) / 10.0f;
    s_axp.vbat_v  = 3.80f + (float)lv_rand(0, 6) / 100.0f;
    s_axp.temp_c  = 32.8f + (float)((int)lv_rand(0, 20) - 10) / 10.0f;
    ui_refresh_dynamic();
#else
    /* 真机：读取 RTC 时间与 AXP202 实时数据 */
    update_RTC_global_variable();
    char hms[16] = {0};
    if (sscanf(RTC_global_variable, "%*s %15s", hms) == 1) {
        lv_label_set_text(s_time_lbl, hms);
    } else {
        lv_label_set_text(s_time_lbl, RTC_global_variable);
    }

    axp_pull_live();
    ui_refresh_dynamic();
#endif
}

