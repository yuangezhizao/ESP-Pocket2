/* QEMU 无触摸输入：用一个多步定时器脚本化演示“弹窗→改开关→确认→刷新”整套交互，
 * 便于截图/录像。真机则由手指触摸驱动同一套逻辑。 */
static void demo_seq_cb(lv_timer_t *t)
{
    (void)t;
    static int step = 0;
    static bool want = true;    /* 每轮翻转 LDO2（关键轨）目标状态 */
    switch (step) {
    case 0:
        power_dialog_open();                 /* 打开开关浮窗 */
        break;
    case 1:
        if (s_dlg_bg) {                      /* 模拟用户拨动 LDO2（关键轨）*/
            want = !want;
            if (want) {
                lv_obj_add_state(s_rail_sw[AXP202_RAIL_LDO2], LV_STATE_CHECKED);
            } else {
                lv_obj_remove_state(s_rail_sw[AXP202_RAIL_LDO2], LV_STATE_CHECKED);
            }
        }
        break;
    case 2:
        dlg_confirm_cb(NULL);                /* 关 LDO2→弹二次确认；开 LDO2→直接生效 */
        break;
    case 3:
        if (s_confirm2_bg) {                 /* 若弹出二次确认，点“仍要关闭” */
            confirm2_accept_cb(NULL);
        }
        break;
    default:
        break;
    }
    step = (step + 1) % 4;                    /* 循环演示，便于录像 */
}
