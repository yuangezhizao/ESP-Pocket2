/* A power-rail row: shows "<mv> mV" in green when enabled, else "OFF" in grey. */
static void rail_row(lv_obj_t *card, int y, const char *name, int mv, bool on)
{
    char b[24];
    if (on) {
        snprintf(b, sizeof(b), "%d mV", mv);
        kv_row(card, y, name, b, ACC_GREEN);
    } else {
        kv_row(card, y, name, "OFF", COL_SUB);
    }
}

